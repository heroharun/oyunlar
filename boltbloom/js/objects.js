  // Kaba carpisma testi (yerel koordinatta)
  BB.shapeContains = function (piece, lx, ly) {
    var hw = piece.w / 2, hh = piece.h / 2;
    switch (piece.s) {
      case 'circle': case 'wheel': case 'gear': case 'gearS':
        return (lx * lx) / (hw * hw) + (ly * ly) / (hh * hh) <= 1.02;
      case 'triangle':
        if (ly > hh || ly < -hh) return false;
        var t = (ly + hh) / piece.h;
        return Math.abs(lx) <= hw * t;
      case 'trapezoid':
        if (Math.abs(ly) > hh) return false;
        var t2 = (ly + hh) / piece.h;
        return Math.abs(lx) <= hw * (0.34 + 0.66 * t2);
      case 'trapInv':
        if (Math.abs(ly) > hh) return false;
        var t3 = 1 - (ly + hh) / piece.h;
        return Math.abs(lx) <= hw * (0.34 + 0.66 * t3);
      default:
        return Math.abs(lx) <= hw && Math.abs(ly) <= hh;
    }
  };

