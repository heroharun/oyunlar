  function rr(w, h, r) {
    var x = -w / 2, y = -h / 2;
    r = Math.min(r, w / 2, h / 2);
    return 'M' + (x + r) + ' ' + y +
      'h' + (w - 2 * r) + 'a' + r + ' ' + r + ' 0 0 1 ' + r + ' ' + r +
      'v' + (h - 2 * r) + 'a' + r + ' ' + r + ' 0 0 1 ' + (-r) + ' ' + r +
      'h' + (-(w - 2 * r)) + 'a' + r + ' ' + r + ' 0 0 1 ' + (-r) + ' ' + (-r) +
      'v' + (-(h - 2 * r)) + 'a' + r + ' ' + r + ' 0 0 1 ' + r + ' ' + (-r) + 'Z';
  }
  function ell(w, h) {
    var a = w / 2, b = h / 2;
    return 'M' + (-a) + ' 0a' + a + ' ' + b + ' 0 1 0 ' + (2 * a) + ' 0a' + a + ' ' + b + ' 0 1 0 ' + (-2 * a) + ' 0Z';
  }
  function gearPath(w, h, teeth) {
    var R = Math.min(w, h) / 2, r = R * 0.78, pts = [], n = teeth || 10;
    for (var i = 0; i < n * 2; i++) {
      var a = (Math.PI * i) / n - Math.PI / 2;
      var rad = i % 2 === 0 ? R : r;
      pts.push([Math.cos(a) * rad, Math.sin(a) * rad]);
    }
    return poly(pts);
  }
  function hexPath(w, h) {
    var a = w / 2, b = h / 2;
    return poly([[-a * 0.5, -b], [a * 0.5, -b], [a, 0], [a * 0.5, b], [-a * 0.5, b], [-a, 0]]);
  }

